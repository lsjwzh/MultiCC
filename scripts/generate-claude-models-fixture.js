'use strict';

// Regenerates native/gateway/tests/fixtures/claude-models.json.
//
//   node scripts/generate-claude-models-fixture.js          # verify
//   node scripts/generate-claude-models-fixture.js --write  # rewrite
//
// The expectations come from the frozen Node oracle
// (tests/helpers/legacy-claude-models-route.js) mounted in a real Express app,
// pointed at a synthetic HOME with two CLI "version" bundles. The older file
// has an older mtime, so resolveClaudeBundle picks the newer one — the same
// layout the Rust integration test materializes (with the same fixed mtimes).
//
// Nothing in the response is clock-dependent: the route body is models/source/
// cached and the cache file is not part of the body, so the JSON is byte
// identical on every run. The `fallback` list is emitted twice (oracle and
// src/claude-models.js) after asserting they agree; the Rust test and the JS
// test both fail if either drifts from this file.
//
// Isolation: its own HOME and working directory under $TMPDIR/claude-models-port/.

const assert = require('node:assert');
const fs = require('node:fs');
const http = require('node:http');
const os = require('node:os');
const path = require('node:path');

const root = path.join(__dirname, '..');
const target = path.join(root, 'native', 'gateway', 'tests', 'fixtures', 'claude-models.json');
const ORACLE_PATH = path.join(root, 'tests', 'helpers', 'legacy-claude-models-route.js');
const NODE_MODULE_PATH = path.join(root, 'src', 'claude-models.js');

// Fixed mtimes keep the bundle selection deterministic even if the test host
// materializes the two files in the opposite order.
const NEWEST_MTIME_MS = 1_700_000_000_000;
const OLDER_MTIME_MS = 1_600_000_000_000;

// The newest bundle carries [1m] for opus 5 / sonnet 4.6 only; the older one
// must never contribute (the newest by mtime wins).
const NEWEST_TEXT = [
  '#!/usr/bin/env node',
  '// release 2.1.300',
  'const models = ["claude-opus-5", "claude-opus-5[1m]", "claude-opus-4-8", "claude-opus-4-8[1m]",',
  '  "claude-opus-4-6", "claude-sonnet-5", "claude-sonnet-4-6",',
  '  "claude-sonnet-4-6[1m]", "claude-fable-5", "claude-haiku-4-5",',
  '  "claude-haiku-4-5-20251001", "claude-opus-4-20250514"];',
  '',
].join('\n');
const OLDER_TEXT = [
  '#!/usr/bin/env node',
  '// release 2.1.200',
  'const models = ["claude-opus-4-5", "claude-sonnet-4-5", "claude-haiku-4-5"];',
  '',
].join('\n');

const HOME_FILES = [
  { path: '.local/share/claude/versions/2.1.200', text: OLDER_TEXT, mtimeMs: OLDER_MTIME_MS },
  { path: '.local/share/claude/versions/2.1.300', text: NEWEST_TEXT, mtimeMs: NEWEST_MTIME_MS },
];

// Order matters: the first GET scans, the second is a cache hit, and the
// refresh spellings re-scan. `refresh[0]=1` is an Express qs array of one,
// whose String() is still "1" — the Rust query parser must agree.
const CASES = [
  { name: 'GET first scan', method: 'GET', url: '/api/claude/models' },
  { name: 'GET cache hit', method: 'GET', url: '/api/claude/models' },
  { name: 'GET refresh 1', method: 'GET', url: '/api/claude/models?refresh=1' },
  { name: 'GET refresh TRUE', method: 'GET', url: '/api/claude/models?refresh=TRUE' },
  { name: 'GET refresh true', method: 'GET', url: '/api/claude/models?refresh=true' },
  { name: 'GET refresh 0', method: 'GET', url: '/api/claude/models?refresh=0' },
  { name: 'GET refresh empty', method: 'GET', url: '/api/claude/models?refresh' },
  { name: 'GET refresh false', method: 'GET', url: '/api/claude/models?refresh=false' },
  { name: 'GET refresh index 0', method: 'GET', url: '/api/claude/models?refresh[0]=1' },
  { name: 'HEAD cache hit', method: 'HEAD', url: '/api/claude/models' },
  { name: 'OPTIONS', method: 'OPTIONS', url: '/api/claude/models' },
  { name: 'GET If-None-Match star', method: 'GET', url: '/api/claude/models', headers: { 'If-None-Match': '*' } },
];

const FALLBACK_CASES = [
  { name: 'GET fallback', method: 'GET', url: '/api/claude/models' },
  // Never cached: a broken CLI is re-probed on every request.
  { name: 'GET fallback again', method: 'GET', url: '/api/claude/models' },
  { name: 'GET fallback refresh 1', method: 'GET', url: '/api/claude/models?refresh=1' },
  { name: 'HEAD fallback', method: 'HEAD', url: '/api/claude/models' },
  { name: 'OPTIONS fallback', method: 'OPTIONS', url: '/api/claude/models' },
  { name: 'GET fallback If-None-Match star', method: 'GET', url: '/api/claude/models', headers: { 'If-None-Match': '*' } },
];

const COMMENT = [
  'Golden responses for native/gateway/tests/claude_models.rs.',
  'Generated by scripts/generate-claude-models-fixture.js from the frozen Node',
  'oracle (tests/helpers/legacy-claude-models-route.js) in a real Express app',
  'with the synthetic HOME below. The response has no clock fields, so the',
  'cases are byte identical on every run. `fallback` is asserted against both',
  'the oracle constant and src/claude-models.js before it is written; the Rust',
  'test and tests/test-claude-models-fallback.js both read this list.',
];

function send(port, { method, url, headers = {} }) {
  return new Promise((resolve, reject) => {
    const request = http.request({ host: '127.0.0.1', port, method, path: url, headers, agent: false }, (response) => {
      const chunks = [];
      response.on('data', (chunk) => chunks.push(chunk));
      response.on('end', () => resolve({ status: response.statusCode, headers: response.headers, body: Buffer.concat(chunks) }));
      response.on('error', reject);
    });
    request.setTimeout(10_000, () => request.destroy(new Error(`${method} ${url}: no answer within 10s`)));
    request.on('error', reject);
    request.end();
  });
}

async function collect(port, cases) {
  const rows = [];
  for (const definition of cases) {
    const response = await send(port, { method: definition.method, url: definition.url, headers: definition.headers });
    const body = response.body.toString('utf8');
    assertStatusBody(definition, response);
    const row = {
      name: definition.name,
      method: definition.method,
      url: definition.url,
    };
    if (definition.headers) row.headers = definition.headers;
    row.status = response.status;
    row.contentType = response.headers['content-type'] || null;
    row.contentEncoding = response.headers['content-encoding'] || null;
    row.contentLength = response.headers['content-length'] || null;
    row.etag = response.headers.etag || null;
    row.allow = response.headers.allow || null;
    row.body = body;
    rows.push(row);
  }
  return rows;
}

function assertStatusBody(definition, response) {
  const body = response.body.toString('utf8');
  if (definition.method === 'OPTIONS') {
    if (response.status !== 200 || body !== 'GET,HEAD') {
      throw new Error(`${definition.name}: unexpected OPTIONS ${response.status} ${JSON.stringify(body)}`);
    }
    return;
  }
  if (definition.method === 'HEAD') {
    if (response.status !== 200 || body !== '') {
      throw new Error(`${definition.name}: unexpected HEAD ${response.status} ${JSON.stringify(body)}`);
    }
    return;
  }
  if (definition.headers && definition.headers['If-None-Match'] === '*') {
    if (response.status !== 304 || body !== '') {
      throw new Error(`${definition.name}: expected 304, got ${response.status}`);
    }
    return;
  }
  const parsed = JSON.parse(body);
  if (response.status !== 200 || !parsed || !Array.isArray(parsed.models)) {
    throw new Error(`${definition.name}: unexpected ${response.status} ${body}`);
  }
}

function writeHome(home, files) {
  fs.rmSync(home, { recursive: true, force: true });
  fs.mkdirSync(home, { recursive: true });
  for (const file of files) {
    const targetFile = path.join(home, file.path);
    fs.mkdirSync(path.dirname(targetFile), { recursive: true });
    fs.writeFileSync(targetFile, file.text);
    const milliseconds = file.mtimeMs;
    fs.utimesSync(targetFile, milliseconds / 1000, milliseconds / 1000);
  }
}

async function mountApp() {
  const express = require('express');
  const ORACLE = require(ORACLE_PATH);
  const app = express();
  ORACLE.mountClaudeModelRoutes(app);
  const server = http.createServer(app);
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  return { server, port: server.address().port };
}

async function runScenario(home, cases) {
  require(ORACLE_PATH)._resetCacheForTest();
  process.env.HOME = home;
  process.env.USERPROFILE = home;
  writeHome(home, HOME_FILES);
  const app = await mountApp();
  try {
    return await collect(app.port, cases);
  } finally {
    await new Promise((resolve) => app.server.close(resolve));
  }
}

async function runFallbackScenario(home, cases) {
  // A missing bundle has key '' and sameBundle treats it as always matching,
  // so the first scenario's cli cache would leak into this one without a reset.
  require(ORACLE_PATH)._resetCacheForTest();
  process.env.HOME = home;
  process.env.USERPROFILE = home;
  fs.rmSync(home, { recursive: true, force: true });
  fs.mkdirSync(home, { recursive: true });
  const app = await mountApp();
  try {
    return await collect(app.port, cases);
  } finally {
    await new Promise((resolve) => app.server.close(resolve));
  }
}

async function build() {
  const work = path.join(os.tmpdir(), 'claude-models-port', `fixture-${process.pid}`);
  const home = path.join(work, 'home');
  const fallbackHome = path.join(work, 'fallback-home');
  const data = path.join(work, 'data');
  for (const dir of [work, data]) fs.mkdirSync(dir, { recursive: true });
  process.env.HOME = home;
  process.env.USERPROFILE = home;
  process.env.TMPDIR = work;
  process.env.MULTICC_DATA_DIR = data;

  const ORACLE = require(ORACLE_PATH);
  const NODE_MODULE = require(NODE_MODULE_PATH);
  assert.deepStrictEqual(
    NODE_MODULE.CLAUDE_MODELS_FALLBACK.map((entry) => ({ ...entry })),
    ORACLE.CLAUDE_MODELS_FALLBACK.map((entry) => ({ ...entry })),
    'src/claude-models.js CLAUDE_MODELS_FALLBACK drifted from the frozen oracle',
  );

  let cases;
  let fallbackCases;
  try {
    cases = await runScenario(home, CASES);
    fallbackCases = await runFallbackScenario(fallbackHome, FALLBACK_CASES);
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }

  const fallback = ORACLE.CLAUDE_MODELS_FALLBACK.map((entry) => ({ ...entry }));
  return {
    comment: COMMENT,
    home: { files: HOME_FILES },
    cases,
    fallbackHome: { files: [] },
    fallbackCases,
    fallback,
  };
}

async function main() {
  const write = process.argv.includes('--write');
  const fixture = await build();
  const next = `${JSON.stringify(fixture, null, 2)}\n`;
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (write) {
    if (current === next) {
      console.log('claude models fixture already current');
      return;
    }
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, next);
    console.log(`Generated ${path.relative(root, target)} (${fixture.cases.length} cases, ${fixture.fallbackCases.length} fallback)`);
    return;
  }
  if (current !== next) {
    console.error(`${path.relative(root, target)} is stale; run node scripts/generate-claude-models-fixture.js --write`);
    process.exit(1);
  }
  console.log(`claude models fixture current: ${fixture.cases.length} cases, ${fixture.fallbackCases.length} fallback`);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}

