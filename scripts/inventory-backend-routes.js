#!/usr/bin/env node
'use strict';
// Conservative source inventory for the Node exit project. This is a review
// index, not a proof of runtime coverage: computed mounts, plugin routes and
// upgrade/SSE dispatch must also be exercised by the integration inventory.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const files = ['server.js', ...execFileSync('rg', ['--files', 'src'], { cwd: root, encoding: 'utf8' }).trim().split('\n').filter(f => /\.(?:js|cjs|mjs)$/.test(f))].sort();
const rows = [];
let lines = 0;
for (const file of files) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const sourceLines = source.split('\n'); lines += sourceLines.length;
  sourceLines.forEach((line, index) => {
    const pattern = /\b((?:\w+\.)?(?:app|router))\.(get|post|put|patch|delete|use|all|head|options)\s*\(/g;
    for (const match of line.matchAll(pattern)) {
      const argument = line.slice(match.index + match[0].length).trim();
      rows.push({ file, line: index + 1, receiver: match[1], method: match[2], argument: argument.slice(0, 170) });
    }
  });
}
const escape = s => s.replaceAll('|', '\\|').replaceAll('`', "'").replace(/\r/g, '');
const output = [
  '# Node HTTP registration inventory', '',
  'Generated by `node scripts/inventory-backend-routes.js`. These are static registration candidates, not a count of public endpoints. Comments, chained registrations, computed paths, factories and conditional/plugin mounts require review against the isolated runtime router stack before Node can be disabled.', '',
  `Scanned ${files.length} backend JavaScript files (${lines} source lines); found ${rows.length} registration candidates.`, '',
  'All entries remain open until the route is served by Rust without a Node handler and its contract/integration coverage is recorded in the exit plan. Already removed Node modules no longer appear here; the gateway document records migrated surfaces.', '',
  '| Source | Method | Receiver | First argument and handler context |', '|---|---|---|---|',
  ...rows.map(r => `| [${r.file}:${r.line}](../${r.file}#L${r.line}) | ${r.method.toUpperCase()} | ${r.receiver} | ${escape(r.argument)} |`), '',
];
const target = path.join(root, 'docs/backend-route-inventory.md');
fs.writeFileSync(target, output.join('\n'));
console.log(JSON.stringify({ files: files.length, sourceLines: lines, candidates: rows.length, output: path.relative(root, target) }));
