//! `src/network/proxy-policy.js`: which proxy a control-plane GET uses.
//!
//! The front door answers `/api/{claude,codex}/subscription` itself, so it has
//! to make the same proxy decision the Node route made through
//! `policy.proxyForUrl` before handing the plan to the Rust HTTP client. This
//! module is the pure half: environment precedence, `scutil --proxy` parsing,
//! NO_PROXY matching, and the cache bookkeeping. Reading `scutil` stays in the
//! gateway (it is I/O); everything here is synchronous and fixture-testable.
//!
//! Semantics come from `src/network/proxy-policy.js` and are pinned by the
//! corpus in `tests/fixtures/outbound-proxy-cases.json`, generated by
//! `scripts/generate-outbound-proxy-corpus.js` from the real JavaScript.

use std::collections::HashMap;

use serde::{Deserialize, Serialize};
use url::Url;

use crate::js::number::string_to_number;
use crate::js::string::{is_js_whitespace_char, JsString};

/// `DIRECT_HOSTS`: loopback is always direct, whatever the policy says.
pub const DIRECT_HOSTS: [&str; 4] = ["localhost", "127.0.0.1", "::1", "[::1]"];

/// Environment variables the policy looks at. A key that exists counts even
/// when its value is empty (`node_modules`-style explicit "no proxy here").
pub type Env = HashMap<String, String>;

/// The six proxy variables plus their no_proxy halves from the process.
pub fn env_from_process() -> Env {
    let mut env = Env::new();
    for key in [
        "http_proxy",
        "HTTP_PROXY",
        "https_proxy",
        "HTTPS_PROXY",
        "all_proxy",
        "ALL_PROXY",
        "no_proxy",
        "NO_PROXY",
    ] {
        if let Some(value) = std::env::var_os(key) {
            env.insert(key.to_string(), value.to_string_lossy().into_owned());
        }
    }
    env
}

/// `hasProxyEnv`: presence, not truthiness.
pub fn has_proxy_env(env: &Env) -> bool {
    [
        "http_proxy",
        "HTTP_PROXY",
        "https_proxy",
        "HTTPS_PROXY",
        "all_proxy",
        "ALL_PROXY",
    ]
    .iter()
    .any(|key| env.contains_key(*key))
}

/// The shape `parseMacSystemProxy` returns.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct SystemProxy {
    pub http_proxy: String,
    pub https_proxy: String,
    pub socks_proxy: String,
    pub exceptions: Vec<String>,
    pub pac_enabled: bool,
}

/// `resolveProxyConfig` output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProxyConfig {
    pub http_proxy: String,
    pub https_proxy: String,
    pub no_proxy: Vec<String>,
    pub mode: &'static str,
}

/// Only the fact that resolution failed matters to the route (it answers
/// `unavailable`); the message is for logs and tests.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProxyError(pub &'static str);

impl std::fmt::Display for ProxyError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(self.0)
    }
}

fn empty(value: &str) -> bool {
    value.is_empty()
}

/// `env[key] ?? env[UPPER]`: an empty string still wins over the other case.
fn lower_or_upper<'a>(env: &'a Env, lower: &str, upper: &str) -> Option<&'a str> {
    env.get(lower)
        .or_else(|| env.get(upper))
        .map(String::as_str)
}

/// `resolveProxyConfig(env, system)`.
pub fn resolve_proxy_config(
    env: &Env,
    system: Option<&SystemProxy>,
) -> Result<ProxyConfig, ProxyError> {
    let explicit = has_proxy_env(env);
    let http = lower_or_upper(env, "http_proxy", "HTTP_PROXY");
    let https = lower_or_upper(env, "https_proxy", "HTTPS_PROXY");
    let all = lower_or_upper(env, "all_proxy", "ALL_PROXY");
    let system_http = system.map(|value| value.http_proxy.as_str()).unwrap_or("");
    let system_https = system.map(|value| value.https_proxy.as_str()).unwrap_or("");
    let http_proxy = if explicit {
        http.or(all).unwrap_or("")
    } else {
        system_http
    };
    let https_proxy = if explicit {
        https.or(http).or(all).unwrap_or("")
    } else {
        system_https
    };
    let socks_or_pac = system
        .map(|value| !value.socks_proxy.is_empty() || value.pac_enabled)
        .unwrap_or(false);
    if !explicit && (empty(http_proxy) || empty(https_proxy)) && socks_or_pac {
        return Err(ProxyError(
            "系统代理仅配置了 SOCKS/PAC；请配置 HTTP(S) 代理，已阻止静默直连",
        ));
    }
    for proxy in [http_proxy, https_proxy] {
        if proxy.is_empty() {
            continue;
        }
        let Ok(parsed) = Url::parse(proxy) else {
            return Err(ProxyError(
                "代理地址必须是 HTTP(S) proxy URL；已阻止静默直连",
            ));
        };
        if !matches!(parsed.scheme(), "http" | "https") {
            return Err(ProxyError(
                "代理地址必须是 HTTP(S) proxy URL；已阻止静默直连",
            ));
        }
    }
    let exceptions: &[String] = if explicit {
        &[]
    } else {
        system
            .map(|value| value.exceptions.as_slice())
            .unwrap_or(&[])
    };
    let raw_no_proxy = env
        .get("no_proxy")
        .or_else(|| env.get("NO_PROXY"))
        .map(String::as_str)
        .unwrap_or("");
    let mut no_proxy: Vec<String> = DIRECT_HOSTS.iter().map(|host| host.to_string()).collect();
    for entry in raw_no_proxy
        .split(|character: char| is_js_whitespace_char(character) || character == ',')
        .filter(|entry| !entry.is_empty())
    {
        if !no_proxy.iter().any(|other| other == entry) {
            no_proxy.push(entry.to_string());
        }
    }
    for exception in exceptions {
        if !no_proxy.iter().any(|other| other == exception) {
            no_proxy.push(exception.clone());
        }
    }
    let mode = if !http_proxy.is_empty() || !https_proxy.is_empty() {
        if explicit {
            "environment-proxy"
        } else {
            "system-proxy"
        }
    } else {
        "direct"
    };
    Ok(ProxyConfig {
        http_proxy: http_proxy.to_string(),
        https_proxy: https_proxy.to_string(),
        no_proxy,
        mode,
    })
}

/// `scutil --proxy`'s text form. `value()` is the first line matching
/// `^\s*KEY\s*:\s*(.*?)\s*$`.
fn value(text: &str, key: &str) -> Option<String> {
    let pattern = format!(r"(?m)^\s*{}\s*:\s*(.*?)\s*$", key);
    let regex = regex::Regex::new(&pattern).ok()?;
    regex.captures(text).map(|captures| captures[1].to_string())
}

fn proxy_entry(text: &str, prefix: &str) -> String {
    if value(text, &format!("{prefix}Enable")).as_deref() != Some("1") {
        return String::new();
    }
    let host = value(text, &format!("{prefix}Proxy")).unwrap_or_default();
    let port = value(text, &format!("{prefix}Port")).unwrap_or_default();
    let port = string_to_number(&JsString::from_rust_str(&port));
    if host.is_empty()
        || !port.is_finite()
        || port.fract() != 0.0
        || !(1.0..=65535.0).contains(&port)
    {
        return String::new();
    }
    let host = if host.contains(':') {
        format!("[{host}]")
    } else {
        host
    };
    let scheme = if prefix == "SOCKS" { "socks5" } else { "http" };
    format!("{scheme}://{host}:{}", port as u64)
}

/// `parseMacSystemProxy(text)`.
pub fn parse_mac_system_proxy(text: &str) -> SystemProxy {
    let mut exceptions = Vec::new();
    if let Ok(regex) = regex::Regex::new(r"ExceptionsList\s*:\s*<array>\s*\{([\s\S]*?)\}") {
        if let Some(list) = regex.captures(text) {
            if let Ok(item) = regex::Regex::new(r"(?m)^\s*\d+\s*:\s*(.+?)\s*$") {
                for line in list[1].split('\n') {
                    if let Some(found) = item.captures(line) {
                        exceptions.push(found[1].to_string());
                    }
                }
            }
        }
    }
    if value(text, "ExcludeSimpleHostnames").as_deref() == Some("1") {
        exceptions.push("<local>".to_string());
    }
    let pac = value(text, "ProxyAutoConfigEnable").as_deref() == Some("1")
        || value(text, "ProxyAutoDiscoveryEnable").as_deref() == Some("1");
    SystemProxy {
        http_proxy: proxy_entry(text, "HTTP"),
        https_proxy: proxy_entry(text, "HTTPS"),
        socks_proxy: proxy_entry(text, "SOCKS"),
        exceptions,
        pac_enabled: pac,
    }
}

/// `ipv4(value)`: four decimal groups, each at most 255, as a number.
fn ipv4(value: &str) -> Option<f64> {
    let parts: Vec<&str> = value.split('.').collect();
    if parts.len() != 4 {
        return None;
    }
    let mut number = 0.0;
    for part in parts {
        if part.is_empty() || !part.bytes().all(|byte| byte.is_ascii_digit()) {
            return None;
        }
        let group = string_to_number(&JsString::from_rust_str(part));
        if !(0.0..=255.0).contains(&group) {
            return None;
        }
        number = number * 256.0 + group;
    }
    Some(number)
}

/// `cidrToRange("10.0.0.0/8")` → `"10.0.0.0-10.255.255.255"`.
pub fn cidr_to_range(entry: &str) -> Option<String> {
    // `const [host, bits] = String(entry).split('/')`: anything after a second
    // slash is ignored by the destructuring assignment.
    let mut parts = entry.split('/');
    let host = parts.next()?;
    let bits = parts.next()?;
    let ip = ipv4(host)?;
    if bits.is_empty() || !bits.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }
    let bits = string_to_number(&JsString::from_rust_str(bits));
    if bits > 32.0 {
        return None;
    }
    let size = 2f64.powi(32 - bits as i32);
    let start = ip - ip % size;
    Some(format!(
        "{}-{}",
        format_ipv4(start),
        format_ipv4(start + size - 1.0)
    ))
}

fn format_ipv4(number: f64) -> String {
    let number = number as u32;
    [24, 16, 8, 0]
        .iter()
        .map(|shift| ((number >> shift) % 256).to_string())
        .collect::<Vec<_>>()
        .join(".")
}

/// `isLoopback(host)`.
pub fn is_loopback(host: &str) -> bool {
    let name = host
        .to_ascii_lowercase()
        .trim_start_matches('[')
        .trim_end_matches(']')
        .to_string();
    name == "localhost"
        || name.ends_with(".localhost")
        || name == "::1"
        || name.starts_with("127.")
        || name.starts_with("::ffff:127.")
        || is_mapped_loopback(&name)
}

fn is_mapped_loopback(name: &str) -> bool {
    let Some(rest) = name.strip_prefix("::ffff:7f") else {
        return false;
    };
    let bytes = rest.as_bytes();
    bytes.len() >= 3 && bytes[..2].iter().all(u8::is_ascii_hexdigit) && bytes[2] == b':'
}

/// `bypassProxy(url, entries)`.
pub fn bypass_proxy(url: &Url, entries: &[String]) -> bool {
    let host = url
        .host_str()
        .unwrap_or("")
        .to_ascii_lowercase()
        .trim_start_matches('[')
        .trim_end_matches(']')
        .to_string();
    if is_loopback(&host) {
        return true;
    }
    let default_port = if matches!(url.scheme(), "https" | "wss") {
        "443"
    } else {
        "80"
    };
    let port = url
        .port()
        .map(|port| port.to_string())
        .unwrap_or_else(|| default_port.to_string());
    entries.iter().any(|raw| {
        let mut item = raw.to_ascii_lowercase();
        if item == "*" {
            return true;
        }
        if item == "<local>" {
            return !host.contains('.') && !host.contains(':');
        }
        if let Ok(regex) = regex::Regex::new(r"^(\[[^\]]+\]|[^:]+):(\d+)$") {
            if let Some(found) = regex.captures(&item) {
                if found[2] != port {
                    return false;
                }
                item = found[1].to_string();
            }
        }
        item = item
            .trim_start_matches('[')
            .trim_end_matches(']')
            .to_string();
        let range = cidr_to_range(&item).unwrap_or_else(|| item.clone());
        if range.contains('-') {
            let mut parts = range.split('-');
            let start = parts.next().and_then(ipv4);
            let end = parts.next().and_then(ipv4);
            let ip = ipv4(&host);
            if let (Some(start), Some(end), Some(ip)) = (start, end, ip) {
                return ip >= start && ip <= end;
            }
        }
        if let Some(suffix) = item.strip_prefix("*.") {
            return host.ends_with(&format!(".{suffix}"));
        }
        if let Some(suffix) = item.strip_prefix('.') {
            return host == suffix || host.ends_with(&item);
        }
        host == item
    })
}

/// The proxy `proxyForUrl` returns for an already-resolved configuration
/// (loopback was handled by the caller, like the JavaScript does).
pub fn proxy_of(config: &ProxyConfig, url: &Url) -> String {
    if bypass_proxy(url, &config.no_proxy) {
        return String::new();
    }
    if matches!(url.scheme(), "https" | "wss") {
        config.https_proxy.clone()
    } else {
        config.http_proxy.clone()
    }
}

/// The policy's system-proxy slot as the gateway keeps it: one last value and
/// the time it was read. `None` means "never read", which is why a read error
/// before any value is an error rather than a direct fallback.
#[derive(Debug, Default, Clone)]
pub struct SystemSlot {
    pub value: Option<SystemProxy>,
    pub checked_at: Option<i64>,
}

impl SystemSlot {
    /// `now() - checkedAt >= refreshMs`; an unread slot is always due.
    pub fn due(&self, now: i64, refresh_ms: i64) -> bool {
        match self.checked_at {
            None => true,
            Some(checked_at) => now - checked_at >= refresh_ms,
        }
    }

    /// Store a successful read; the stamp is taken after it, like Node.
    pub fn store(&mut self, value: SystemProxy, now: i64) {
        self.value = Some(value);
        self.checked_at = Some(now);
    }
}

/// `createProxyPolicy`'s system-proxy slot plus the TTL decision.
#[derive(Debug, Clone)]
pub struct Cache {
    pub slot: SystemSlot,
    pub refresh_ms: i64,
}

impl Default for Cache {
    fn default() -> Self {
        Self {
            slot: SystemSlot::default(),
            refresh_ms: 30_000,
        }
    }
}

impl Cache {
    /// Apply one discovery outcome. A read error keeps the last known policy;
    /// before any value it propagates (never a silent direct fallback).
    pub fn accept(
        &mut self,
        now: i64,
        read: Result<SystemProxy, ProxyError>,
    ) -> Result<(), ProxyError> {
        match read {
            Ok(value) => {
                self.slot.store(value, now);
                Ok(())
            }
            Err(error) => {
                if self.slot.value.is_none() {
                    return Err(error);
                }
                self.slot.checked_at = Some(now);
                Ok(())
            }
        }
    }

    /// `configuration()`: read the system proxy on darwin when the environment
    /// carries none and the last read is past `refresh_ms`.
    pub fn configuration(
        &mut self,
        env: &Env,
        platform: &str,
        now: i64,
        read_system: impl FnOnce() -> Result<SystemProxy, ProxyError>,
    ) -> Result<ProxyConfig, ProxyError> {
        if platform == "darwin" && !has_proxy_env(env) && self.slot.due(now, self.refresh_ms) {
            self.accept(now, read_system())?;
        }
        resolve_proxy_config(env, self.slot.value.as_ref())
    }
}

